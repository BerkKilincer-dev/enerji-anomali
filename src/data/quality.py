"""Data quality report for the processed dataset.

Usage: python -m src.data.quality
Writes reports/data/quality.json, quality.md and figures.
"""

from __future__ import annotations

import argparse
import logging
from pathlib import Path

import pandas as pd

from src.common.report import md_table, write_json
from src.common.runs import runs
from src.config import get_settings
from src.data.dataset import ensure_tables, model_frame
from src.data.prepare import KBTU_SITE_IDS

log = logging.getLogger(__name__)


def label_events(df: pd.DataFrame) -> pd.Series:
    """Length of every run of consecutive anomaly hours, per building."""
    run = runs(df["anomaly"].to_numpy() == 1, df["building_id"].to_numpy())
    return pd.Series(run[run >= 0]).value_counts()


def summarize(df: pd.DataFrame, buildings: pd.DataFrame) -> dict:
    present = df[~df["is_missing"]]
    median = present.groupby("building_id")["kwh"].transform("median")
    ratio = present["kwh"] / median
    same_as_prev = present.groupby("building_id")["kwh"].diff().eq(0) & present["kwh"].gt(0)
    events = label_events(df)
    weather_cols = ["air_temp", "dew_temp", "wind_speed", "cloud_cover", "precip_1h"]

    def rate_by(col: str) -> dict:
        g = present.groupby(col)["anomaly"]
        return (
            pd.DataFrame(
                {
                    "buildings": present.groupby(col)["building_id"].nunique(),
                    "anomaly_rate": g.mean(),
                }
            )
            .round(4)
            .to_dict("index")
        )

    by_hour_peak = df.groupby(["weather_key", df["ts"].dt.hour])["air_temp"].mean()
    temp_peak_hour = by_hour_peak.groupby(level=0).idxmax().map(lambda t: t[1])

    return {
        "rows": len(df),
        "buildings": int(df["building_id"].nunique()),
        "period": [df["ts"].min(), df["ts"].max()],
        "missing_rate": float(df["is_missing"].mean()),
        "rows_added_to_complete_grid": int((~df["in_source"]).sum()),
        "anomaly_rate": float(present["anomaly"].mean()),
        "anomaly_on_missing_readings": int(df.loc[df["is_missing"], "anomaly"].sum()),
        "zero_reading_share": float(present["kwh"].eq(0).mean()),
        "flatline_share": float(same_as_prev.mean()),
        "anomaly_rate_on_flatline": float(present.loc[same_as_prev, "anomaly"].mean()),
        "kbtu_converted_buildings": int(buildings["site_id"].isin(KBTU_SITE_IDS).sum()),
        "label_events": {
            "count": len(events),
            "length_hours": events.describe(percentiles=[0.5, 0.75, 0.9, 0.95, 0.99]).to_dict(),
        },
        "value_vs_building_median": {
            "normal": ratio[present["anomaly"] == 0]
            .quantile([0.05, 0.25, 0.5, 0.75, 0.95])
            .to_dict(),
            "anomaly": ratio[present["anomaly"] == 1]
            .quantile([0.05, 0.25, 0.5, 0.75, 0.95])
            .to_dict(),
        },
        "anomaly_rate_by_split": rate_by("split"),
        "anomaly_rate_by_primary_use": rate_by("primary_use"),
        "anomaly_rate_by_site": rate_by("weather_key"),
        "anomaly_rate_by_month": present.groupby(present["ts"].dt.month)["anomaly"]
        .mean()
        .to_dict(),
        "anomaly_rate_by_hour": present.groupby(present["ts"].dt.hour)["anomaly"].mean().to_dict(),
        "weather_missing_rate": df[weather_cols].isna().mean().to_dict(),
        "air_temp_peak_hour_by_site": temp_peak_hour.to_dict(),
        "per_building_anomaly_rate": present.groupby("building_id")["anomaly"]
        .mean()
        .describe()
        .to_dict(),
    }


def _section(title: str, table: dict, index_name: str) -> str:
    frame = pd.DataFrame.from_dict(table, orient="index").rename_axis(index_name)
    return f"## {title}\n\n{md_table(frame, index=True)}\n"


def to_markdown(s: dict) -> str:
    q = s["value_vs_building_median"]
    ev = s["label_events"]["length_hours"]
    profile = pd.DataFrame({"normal": q["normal"], "anomaly": q["anomaly"]}).rename_axis("quantile")
    return "\n".join(
        [
            "# Data quality report",
            "",
            "Generated by `python -m src.data.quality` from the processed LEAD + BDG2 tables.",
            "",
            "## Overview",
            "",
            f"- Rows: {s['rows']:,} ({s['buildings']} buildings, hourly, "
            f"{s['period'][0]:%Y-%m-%d} to {s['period'][1]:%Y-%m-%d})",
            f"- Missing readings: {s['missing_rate']:.2%} "
            f"({s['rows_added_to_complete_grid']:,} rows added to complete the hourly grid)",
            f"- Anomaly rate on present readings: {s['anomaly_rate']:.2%}; "
            f"labels on missing readings: {s['anomaly_on_missing_readings']}",
            f"- Zero readings: {s['zero_reading_share']:.3%}; flatline (same as previous hour): "
            f"{s['flatline_share']:.2%}, anomaly rate there {s['anomaly_rate_on_flatline']:.2%}",
            f"- Buildings converted from kBTU to kWh (site 0): {s['kbtu_converted_buildings']}",
            f"- Label events: {s['label_events']['count']:,}, median length {ev['50%']:.0f} h, "
            f"p90 {ev['90%']:.0f} h, max {ev['max']:.0f} h",
            "",
            "## Reading value relative to the building median",
            "",
            "Most labeled anomalies are drops (near-zero or reduced readings), not spikes.",
            "",
            md_table(profile.round(3), index=True),
            "",
            _section("Anomaly rate by split", s["anomaly_rate_by_split"], "split"),
            _section(
                "Anomaly rate by primary use", s["anomaly_rate_by_primary_use"], "primary_use"
            ),
            _section("Anomaly rate by site", s["anomaly_rate_by_site"], "site"),
            "## Weather alignment",
            "",
            "Average air temperature peaks in the afternoon at every site, so BDG2 weather is",
            "already in site local time, the same clock as the meter readings. No shift applied.",
            "",
            md_table(
                pd.Series(s["air_temp_peak_hour_by_site"], name="peak_hour")
                .rename_axis("site")
                .to_frame(),
                index=True,
            ),
            "",
        ]
    )


def plot(df: pd.DataFrame, s: dict, out_dir: Path) -> list[Path]:
    try:
        import matplotlib.pyplot as plt
    except ImportError:
        log.warning("matplotlib missing, skipping figures")
        return []
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = []

    fig, ax = plt.subplots(1, 2, figsize=(11, 3.5))
    pd.Series(s["anomaly_rate_by_month"]).plot.bar(ax=ax[0], color="#c0392b")
    ax[0].set(title="Anomaly rate by month", xlabel="month", ylabel="rate")
    pd.Series(s["anomaly_rate_by_hour"]).plot(ax=ax[1], color="#2c3e50")
    ax[1].set(title="Anomaly rate by hour of day", xlabel="hour", ylabel="rate")
    fig.tight_layout()
    paths.append(out_dir / "anomaly_rates.png")
    fig.savefig(paths[-1], dpi=110)
    plt.close(fig)

    rates = df.groupby("building_id")["anomaly"].mean().sort_values()
    example = rates.index[len(rates) // 2]
    b = df[(df["building_id"] == example) & df["ts"].dt.month.between(6, 8)]
    fig, ax = plt.subplots(figsize=(11, 3.5))
    ax.plot(b["ts"], b["kwh"], lw=0.7, color="#2c3e50", label="kWh")
    hits = b[b["anomaly"] == 1]
    ax.scatter(hits["ts"], hits["kwh"], s=6, color="#c0392b", label="labeled anomaly", zorder=3)
    ax.set(title=f"Building {example}, June-August 2016", ylabel="kWh")
    ax.legend(loc="upper right")
    fig.tight_layout()
    paths.append(out_dir / "example_building.png")
    fig.savefig(paths[-1], dpi=110)
    plt.close(fig)
    return paths


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    settings = get_settings()
    tables = ensure_tables(settings)
    df = model_frame(tables)
    summary = summarize(df, tables.buildings)
    out = settings.reports_dir / "data"
    write_json(out / "quality.json", summary)
    (out / "quality.md").write_text(to_markdown(summary), encoding="utf-8")
    for path in plot(df, summary, out / "figures"):
        print(path)
    print(out / "quality.md")


if __name__ == "__main__":
    main()
