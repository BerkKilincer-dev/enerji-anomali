    PERFORM create_hypertable('readings', 'ts', if_not_exists => TRUE, migrate_data => TRUE);
    PERFORM create_hypertable('predictions', 'ts', if_not_exists => TRUE, migrate_data => TRUE);
EXCEPTION WHEN OTHERS THEN
    RAISE NOTICE 'timescaledb unavailable, using plain tables: %', SQLERRM;
END $$;
