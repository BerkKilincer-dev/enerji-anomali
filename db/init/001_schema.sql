-- Idempotent schema: core, telemetry, ml and ops; timestamps are building local time.
CREATE SCHEMA IF NOT EXISTS core;
CREATE SCHEMA IF NOT EXISTS telemetry;
CREATE SCHEMA IF NOT EXISTS ml;
CREATE SCHEMA IF NOT EXISTS ops;

-- Databases created before the split keep their data: tables move out of public once.
DO $$
DECLARE
    m record;
BEGIN
    DROP VIEW IF EXISTS public.readings_enriched, public.daily_kpis,
        public.current_anomalies, public.current_predictions;
    FOR m IN SELECT * FROM (VALUES
        ('tenants', 'core'), ('users', 'core'), ('buildings', 'core'), ('assets', 'core'),
        ('meters', 'core'), ('weather', 'telemetry'), ('readings', 'telemetry'),
        ('scoring_state', 'ml'), ('predictions', 'ml'), ('anomalies', 'ml'),
        ('anomaly_feedback', 'ml'), ('model_artifacts', 'ml')
    ) AS t (name, target)
    LOOP
        IF to_regclass('public.' || m.name) IS NOT NULL
           AND to_regclass(m.target || '.' || m.name) IS NULL THEN
            EXECUTE format('ALTER TABLE public.%I SET SCHEMA %I', m.name, m.target);
        END IF;
    END LOOP;
END $$;

-- Identity: a tenant is one customer company; users with no tenant are platform staff.
CREATE TABLE IF NOT EXISTS core.tenants (
    tenant_id   INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL UNIQUE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- Company and contract details; ADD COLUMN IF NOT EXISTS upgrades older databases.
ALTER TABLE core.tenants
    ADD COLUMN IF NOT EXISTS tax_number TEXT UNIQUE CHECK (tax_number ~ '^[0-9]{10,11}$'),
    ADD COLUMN IF NOT EXISTS tax_office TEXT,
    ADD COLUMN IF NOT EXISTS city TEXT,
    ADD COLUMN IF NOT EXISTS address TEXT,
    ADD COLUMN IF NOT EXISTS contact_name TEXT,
    ADD COLUMN IF NOT EXISTS contact_email TEXT,
    ADD COLUMN IF NOT EXISTS contact_phone TEXT,
    ADD COLUMN IF NOT EXISTS plan TEXT,
    ADD COLUMN IF NOT EXISTS status TEXT NOT NULL DEFAULT 'pilot'
        CHECK (status IN ('pilot', 'active', 'inactive')),
    ADD COLUMN IF NOT EXISTS dpa_signed_on DATE;

CREATE TABLE IF NOT EXISTS core.users (
    user_id     INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    tenant_id   INT REFERENCES core.tenants,
    email       TEXT NOT NULL UNIQUE CHECK (email = lower(email)),
    name        TEXT,
    role        TEXT NOT NULL CHECK (role IN ('admin', 'operator', 'viewer')),
    active      BOOLEAN NOT NULL DEFAULT true,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- Dashboard login: scrypt hash from src/api/auth.py; NULL means the user cannot sign in yet.
ALTER TABLE core.users ADD COLUMN IF NOT EXISTS password_hash TEXT;

-- Signed-in sessions; only the SHA-256 of the cookie token is stored.
CREATE TABLE IF NOT EXISTS core.sessions (
    token_hash  TEXT PRIMARY KEY,
    user_id     INT NOT NULL REFERENCES core.users ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at  TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON core.sessions (user_id);

-- One site (factory, office, store) of a tenant; LEAD keeps dataset ids, customers start at 100000.
CREATE TABLE IF NOT EXISTS core.buildings (
    building_id        INT GENERATED BY DEFAULT AS IDENTITY (START WITH 100000) PRIMARY KEY,
    tenant_id          INT REFERENCES core.tenants,
    external_id        TEXT NOT NULL UNIQUE,
    name               TEXT,
    source             TEXT NOT NULL DEFAULT 'customer',
    site_id            SMALLINT,
    weather_key        TEXT NOT NULL,
    primary_use        TEXT,
    sub_use            TEXT,
    square_feet        DOUBLE PRECISION CHECK (square_feet > 0),
    year_built         SMALLINT,
    timezone           TEXT NOT NULL DEFAULT 'Europe/Istanbul',
    country            TEXT CHECK (country ~ '^[A-Z]{2}$'),
    lat                DOUBLE PRECISION CHECK (lat BETWEEN -90 AND 90),
    lng                DOUBLE PRECISION CHECK (lng BETWEEN -180 AND 180),
    tariff_tl_per_kwh  DOUBLE PRECISION CHECK (tariff_tl_per_kwh >= 0),
    split              TEXT CHECK (split IN ('train', 'val', 'test')),
    active             BOOLEAN NOT NULL DEFAULT true,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- Segments from src/data/segments.py; the check is rebuilt on every run, so new ones apply.
ALTER TABLE core.buildings ADD COLUMN IF NOT EXISTS segment TEXT;
ALTER TABLE core.buildings DROP CONSTRAINT IF EXISTS buildings_segment_check,
    ADD CONSTRAINT buildings_segment_check CHECK (segment IN (
        'office', 'mall', 'retail', 'hotel', 'hospital', 'education', 'factory', 'warehouse',
        'data_center', 'residential', 'public', 'other'));

-- Weekly hours or shifts, ISO weekday (1 = Monday); closes at or before opens runs past midnight.
CREATE TABLE IF NOT EXISTS core.operating_hours (
    building_id  INT NOT NULL REFERENCES core.buildings,
    weekday      SMALLINT NOT NULL CHECK (weekday BETWEEN 1 AND 7),
    opens        TIME NOT NULL,
    closes       TIME NOT NULL,
    PRIMARY KEY (building_id, weekday, opens)
);

CREATE TABLE IF NOT EXISTS core.planned_downtime (
    id           BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    building_id  INT NOT NULL REFERENCES core.buildings,
    starts_at    TIMESTAMP NOT NULL,
    ends_at      TIMESTAMP NOT NULL CHECK (ends_at > starts_at),
    kind         TEXT NOT NULL CHECK (kind IN ('holiday', 'maintenance', 'shutdown')),
    note         TEXT CHECK (length(note) <= 500),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_downtime_building ON core.planned_downtime (building_id, starts_at);

-- Asset tree inside a building: production lines and machines, nested through parent_id.
CREATE TABLE IF NOT EXISTS core.assets (
    asset_id     INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    building_id  INT NOT NULL REFERENCES core.buildings,
    parent_id    INT REFERENCES core.assets,
    kind         TEXT NOT NULL CHECK (kind IN ('line', 'machine', 'zone')),
    name         TEXT NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_assets_building ON core.assets (building_id);
ALTER TABLE core.assets ADD COLUMN IF NOT EXISTS equipment_type TEXT
    CHECK (equipment_type IN ('klima', 'kompresor', 'aydinlatma', 'sogutma', 'plc', 'genel'));

-- Physical meters; readings hold the main meter of each building, submeters come later.
CREATE TABLE IF NOT EXISTS core.meters (
    meter_id     INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    building_id  INT NOT NULL REFERENCES core.buildings,
    asset_id     INT REFERENCES core.assets,
    external_id  TEXT NOT NULL UNIQUE,
    is_main      BOOLEAN NOT NULL DEFAULT false,
    unit         TEXT NOT NULL DEFAULT 'kWh' CHECK (unit IN ('kWh', 'Wh', 'MWh')),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_meters_one_main ON core.meters (building_id) WHERE is_main;

CREATE TABLE IF NOT EXISTS telemetry.weather (
    weather_key         TEXT NOT NULL,
    ts                  TIMESTAMP NOT NULL,
    air_temp            DOUBLE PRECISION,
    dew_temp            DOUBLE PRECISION,
    wind_speed          DOUBLE PRECISION,
    cloud_cover         DOUBLE PRECISION,
    precip_1h           DOUBLE PRECISION,
    sea_level_pressure  DOUBLE PRECISION,
    source              TEXT NOT NULL DEFAULT 'open-meteo',
    PRIMARY KEY (weather_key, ts)
);

-- Hourly readings from every source; NULL kwh = no value, NULL anomaly = not labeled.
CREATE TABLE IF NOT EXISTS telemetry.readings (
    building_id   INT NOT NULL REFERENCES core.buildings,
    ts            TIMESTAMP NOT NULL,
    kwh           DOUBLE PRECISION CHECK (kwh >= 0),
    air_temp      DOUBLE PRECISION,
    is_weekend    BOOLEAN GENERATED ALWAYS AS (extract(isodow FROM ts) >= 6) STORED,
    is_missing    BOOLEAN GENERATED ALWAYS AS (kwh IS NULL) STORED,
    meter_raw     DOUBLE PRECISION,
    anomaly       SMALLINT CHECK (anomaly IN (0, 1)),
    quality       TEXT,
    source        TEXT NOT NULL DEFAULT 'customer',
    received_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (building_id, ts)
);

-- Last hour the scoring service processed, per building.
CREATE TABLE IF NOT EXISTS ml.scoring_state (
    building_id     INT PRIMARY KEY REFERENCES core.buildings,
    last_scored_ts  TIMESTAMP NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Hourly model output; origin 'batch' = offline evaluation, 'live' = scoring service.
CREATE TABLE IF NOT EXISTS ml.predictions (
    building_id     INT NOT NULL REFERENCES core.buildings,
    ts              TIMESTAMP NOT NULL,
    origin          TEXT NOT NULL CHECK (origin IN ('batch', 'live')),
    kwh             DOUBLE PRECISION,
    expected_kwh    DOUBLE PRECISION,
    detector_score  DOUBLE PRECISION,
    residual_score  DOUBLE PRECISION,
    rule_score      DOUBLE PRECISION,
    rule_type       TEXT,
    source          TEXT CHECK (source IN ('rule', 'ml_sup', 'ml_unsup')),
    alarm           BOOLEAN NOT NULL,
    model_version   TEXT NOT NULL,
    PRIMARY KEY (building_id, ts, origin)
);

CREATE TABLE IF NOT EXISTS ml.anomalies (
    id              BIGSERIAL PRIMARY KEY,
    building_id     INT NOT NULL REFERENCES core.buildings,
    ts_start        TIMESTAMP NOT NULL,
    ts_end          TIMESTAMP NOT NULL CHECK (ts_end >= ts_start),
    score           DOUBLE PRECISION,
    source          TEXT CHECK (source IN ('rule', 'ml_sup', 'ml_unsup')),
    rule_type       TEXT,
    excess_kwh      DOUBLE PRECISION,
    est_cost_tl     DOUBLE PRECISION,
    explanation     TEXT,
    origin          TEXT NOT NULL DEFAULT 'live' CHECK (origin IN ('batch', 'live')),
    model_version   TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (building_id, ts_start, origin)
);
-- Optional Turkish advice written by an LLM once an event has ended (src/scoring/advice.py).
ALTER TABLE ml.anomalies ADD COLUMN IF NOT EXISTS advice TEXT CHECK (length(advice) <= 2000);
-- waste = consumption above expected, with a TL cost; data_issue = stuck or silent meter, no cost.
ALTER TABLE ml.anomalies ADD COLUMN IF NOT EXISTS category TEXT
    CHECK (category IN ('waste', 'data_issue'));

-- Operator verdicts (training labels); the time range survives a re-published anomaly.
CREATE TABLE IF NOT EXISTS ml.anomaly_feedback (
    id            BIGSERIAL PRIMARY KEY,
    anomaly_id    BIGINT REFERENCES ml.anomalies ON DELETE SET NULL,
    building_id   INT NOT NULL REFERENCES core.buildings,
    ts_start      TIMESTAMP NOT NULL,
    ts_end        TIMESTAMP NOT NULL CHECK (ts_end >= ts_start),
    verdict       TEXT NOT NULL,
    note          TEXT CHECK (length(note) <= 1000),
    created_by    TEXT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_anomaly_feedback_anomaly ON ml.anomaly_feedback (anomaly_id);
-- Recommendation status too: sent = told the business, applied = the business acted on it.
-- Re-created on every run so databases made with the older, shorter list accept the new ones.
ALTER TABLE ml.anomaly_feedback DROP CONSTRAINT IF EXISTS anomaly_feedback_verdict_check;
ALTER TABLE ml.anomaly_feedback ADD CONSTRAINT anomaly_feedback_verdict_check
    CHECK (verdict IN ('confirmed', 'false_alarm', 'planned', 'sent', 'applied'));

CREATE TABLE IF NOT EXISTS ml.model_artifacts (
    id              BIGSERIAL PRIMARY KEY,
    name            TEXT NOT NULL,
    version         TEXT NOT NULL,
    meta            JSONB NOT NULL,
    expected_model  TEXT NOT NULL,
    detector_model  TEXT NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (name, version)
);

-- Alert and work-order tables were never used; databases made before 2026-10-30 drop them.
DROP TABLE IF EXISTS ops.notifications, ops.alert_settings, ops.work_orders;

-- Live demo switch: the panel's start and stop buttons write it, the live-demo service
-- (src/ingest/live_demo.py) polls it. One row; run_id grows on every start, which makes the
-- service wipe the previous run and play from the beginning.
CREATE TABLE IF NOT EXISTS ops.live_demo (
    id            SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    running       BOOLEAN NOT NULL DEFAULT false,
    run_id        INT NOT NULL DEFAULT 0,
    started_at    TIMESTAMPTZ,
    tenant_id     INT REFERENCES core.tenants,
    heartbeat_at  TIMESTAMPTZ,
    sim_ts        TIMESTAMP
);
INSERT INTO ops.live_demo (id) VALUES (1) ON CONFLICT DO NOTHING;

-- Once the scoring service covers a building, its live output replaces the offline batch.
CREATE OR REPLACE VIEW ml.current_predictions AS
SELECT p.* FROM ml.predictions p
WHERE p.origin = 'live'
   OR NOT EXISTS (SELECT 1 FROM ml.scoring_state s WHERE s.building_id = p.building_id);

CREATE OR REPLACE VIEW ml.current_anomalies AS
SELECT a.* FROM ml.anomalies a
WHERE a.origin = 'live'
   OR NOT EXISTS (SELECT 1 FROM ml.scoring_state s WHERE s.building_id = a.building_id);

-- Model input in one place: readings with building metadata and weather.
CREATE OR REPLACE VIEW ml.readings_enriched AS
SELECT r.building_id, r.ts, r.kwh, r.anomaly, r.is_missing, r.is_weekend,
       b.primary_use, b.segment, b.square_feet, b.split,
       w.air_temp, w.dew_temp, w.wind_speed, w.cloud_cover, w.precip_1h
FROM telemetry.readings r
JOIN core.buildings b USING (building_id)
LEFT JOIN telemetry.weather w ON w.weather_key = b.weather_key AND w.ts = r.ts;

-- Daily KPIs for reporting; partial and merged hours count as missing, as in the models.
CREATE OR REPLACE VIEW ops.daily_kpis AS
SELECT r.building_id, r.ts::date AS day,
       sum(r.kwh) FILTER (WHERE NOT r.missing) AS kwh,
       sum(p.expected_kwh) FILTER (WHERE NOT r.missing) AS expected_kwh,
       sum(greatest(r.kwh - p.expected_kwh, 0)) FILTER (WHERE p.alarm AND NOT r.missing)
           AS excess_kwh,
       count(*) FILTER (WHERE p.alarm) AS alarm_hours,
       count(*) FILTER (WHERE r.missing) AS missing_hours
FROM (SELECT building_id, ts, kwh,
             kwh IS NULL OR coalesce(quality IN ('partial', 'merged'), false) AS missing
      FROM telemetry.readings) r
LEFT JOIN ml.current_predictions p USING (building_id, ts)
GROUP BY r.building_id, r.ts::date;

-- TimescaleDB is optional: use it when the server offers it, plain tables otherwise.
DO $$
BEGIN
    CREATE EXTENSION IF NOT EXISTS timescaledb SCHEMA public;
    PERFORM public.create_hypertable(
        'telemetry.readings', 'ts', if_not_exists => TRUE, migrate_data => TRUE);
    PERFORM public.create_hypertable(
        'ml.predictions', 'ts', if_not_exists => TRUE, migrate_data => TRUE);
EXCEPTION WHEN OTHERS THEN
    RAISE NOTICE 'timescaledb unavailable, using plain tables: %', SQLERRM;
END $$;
